'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const bat = fs.readFileSync(path.join(root, 'release.bat'), 'utf8');
const ps = fs.readFileSync(path.join(root, 'publish_to_monitor.ps1'), 'utf8');
const changelog = fs.readFileSync(path.join(root, 'CHANGELOG.md'), 'utf8');
assert.match(bat, /https:\/\/pdfstudio\.shares\.zrok\.io\/pdfstudio-monitor/, 'public zrok target is configured');
assert.match(bat, /http:\/\/192\.168\.254\.110:8080\/pdfstudio-monitor/, 'local Monitor target is shown in the menu');
assert.match(bat, /Choose 1, 2, or 3 \[3\]/, 'interactive selection defaults to automatic local-first fallback (same as legacy)');
assert.match(bat, /publish_to_monitor\.ps1" -Target "!TARGET!" !EXTRA_ARGS!/, 'chosen target is passed to the uploader exactly like the legacy release.bat');
assert.match(bat, /EnableDelayedExpansion/, 'same batch structure as the legacy release.bat');
assert.match(bat, /noupload/, 'build-only mode remains supported');
assert.match(bat, /-Force/, 'forced publish remains supported');
assert.match(bat, /-NoZip/, 'raw EXE option is forwarded');
assert.match(bat, /ProductName -ne 'PDF Studio'/, 'wrong product executable cannot be published');
assert.match(bat, /EXE version and package\.json version differ/, 'mismatched release version blocks publishing');
assert.match(ps, /System\.Net\.Http\.HttpClient/, 'uploader uses HttpClient (same as legacy) so every Monitor error body is readable');
assert.doesNotMatch(ps, /Invoke-RestMethod/, 'Invoke-RestMethod hides error bodies on Windows PowerShell 5.1');
assert.match(ps, /action=begin/);
assert.match(ps, /action=chunk/);
assert.match(ps, /action=finish/);
assert.match(ps, /Get-FileHash .*SHA256/);
assert.match(ps, /enc=base64/, 'base64 chunks remain available for ZIP packages on public routes');
assert.match(ps, /-Target auto|'auto', 'public', 'local'/, 'auto/public/local targets are supported');
assert.match(ps, /Test-MonitorTcpEndpoint/, 'auto mode avoids slow LAN timeouts');
assert.match(ps, /package = \$package/, 'publisher identifies compressed package to Monitor');
assert.match(ps, /exe_sha256 = \$exeSha/, 'publisher sends original EXE SHA-256 for server validation');
assert.match(ps, /\* 0\.95/, 'ZIP is used only when it saves at least 5%');
assert.match(ps, /rejected the release at the final step \(HTTP/, 'finalization failures print the Monitor message');
assert.match(ps, /FromMinutes\(45\)/, 'finish has a long timeout for a ~150 MB release');
assert.match(ps, /PDFSTUDIO_MONITOR_KEY/, 'API key can be supplied securely through environment');
assert.match(ps, /monitor-key\.txt/, 'API key file is supported');
assert.doesNotMatch(ps, /X-Api-Key'?\s*=\s*['"](?:[a-f0-9]{16,}|.{20,})['"]/, 'no hardcoded API key');
assert.doesNotMatch(ps, /DefaultApiKey|UsageTracker/, 'no legacy source-constant key lookup');
assert.match(changelog, /^## 3\.0\.4/m, 'release notes include current version section');
console.log('V3 release target, compressed package, fallback, and Monitor publisher regression checks passed.');
