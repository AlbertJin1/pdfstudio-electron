'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const bat = fs.readFileSync(path.join(root, 'release.bat'), 'utf8');
const ps = fs.readFileSync(path.join(root, 'publish_to_monitor.ps1'), 'utf8');
const changelog = fs.readFileSync(path.join(root, 'CHANGELOG.md'), 'utf8');
assert.match(bat, /https:\/\/pdfstudio\.shares\.zrok\.io\/pdfstudio-monitor/, 'public zrok target is configured');
assert.match(bat, /http:\/\/192\.168\.254\.110:8080\/pdfstudio-monitor/, 'local Monitor target is configured');
assert.match(bat, /choice \/c 12/, 'interactive target selection is provided');
assert.match(bat, /-MonitorUrl "%MONITOR_BASE%"/, 'chosen base URL is passed to the uploader');
assert.match(bat, /noupload/, 'build-only mode remains supported');
assert.match(bat, /-Force/, 'forced publish remains supported');
assert.match(bat, /-NoZip/, 'raw EXE compatibility option is documented and forwarded');
assert.match(bat, /ProductName -ne 'PDF Studio'/, 'wrong product executable cannot be published');
assert.match(bat, /package\.json version differs|EXE version and package\.json version differ/, 'mismatched release version blocks publishing');
assert.match(ps, /api\/upload\.php/, 'publisher uses current Monitor upload API');
assert.match(ps, /public\/api\/upload\.php/, 'publisher supports hosted public API path');
assert.match(ps, /\/upload\.php/, 'publisher supports legacy PDF Studio API route');
assert.match(ps, /action=begin/);
assert.match(ps, /action=chunk/);
assert.match(ps, /action=finish/);
assert.match(ps, /Get-FileHash .*SHA256/);
assert.match(ps, /enc=base64/, 'current API chunk uploads use gateway-friendly base64');
assert.match(ps, /New-ExeZip/, 'publisher creates a compressed executable package');
assert.match(ps, /package = 'zip'/, 'publisher identifies compressed package to Monitor');
assert.match(ps, /exe_size = \$ExeSize/, 'publisher sends original EXE size for server validation');
assert.match(ps, /exe_sha256 = \$ExeSha256/, 'publisher sends original EXE SHA-256 for server validation');
assert.match(ps, /did not confirm ZIP package support/, 'unsupported monitors trigger a safe raw EXE fallback');
assert.match(ps, /ActiveApiUrl/, 'one API route remains pinned throughout a resumable upload');
assert.match(ps, /rejected the ZIP package format/, 'monitors that explicitly reject ZIP are retried with raw EXE');
assert.match(ps, /PDFSTUDIO_MONITOR_KEY/, 'API key can be supplied securely through environment');
assert.doesNotMatch(ps, /X-Api-Key\s*=\s*['"](?:[a-f0-9]{16,}|.{20,})['"]/, 'no hardcoded API key');
assert.match(changelog, /^## 3\.0\.5/m, 'release notes include current version section');
console.log('V3 release target, compressed package, fallback, and Monitor publisher regression checks passed.');
