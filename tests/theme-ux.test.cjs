'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const read = (file) => fs.readFileSync(path.join(root, file), 'utf8');

const preferences = read('src/constants/preferences.js');
const preferenceHook = read('src/hooks/usePreferences.js');
const systemThemeHook = read('src/hooks/useSystemDarkTheme.js');
const appearance = read('src/views/settings/AppearanceTab.jsx');
const titlebar = read('src/components/layout/TitleBar.jsx');
const preload = read('electron/preload.cjs');
const main = read('electron/main.cjs');
const splash = read('index.html');
const css = read('src/styles/workspace-polish.css');
const toggle = read('src/components/common/SettingToggle.jsx');

assert.match(preferences, /theme: 'system'/, 'System theme should be the default on a clean installation');
assert.match(preferences, /saved\.themeModeVersion === 1[\s\S]*\['system', 'light', 'dark'\]\.includes\(saved\.theme\)/, 'Persisted theme mode should be validated and legacy fixed modes migrated to System');
assert.match(systemThemeHook, /prefers-color-scheme:\s*dark/, 'Web fallback must follow the operating system media preference');
assert.match(systemThemeHook, /getSystemTheme/, 'Electron native theme should be read on startup');
assert.match(systemThemeHook, /onSystemThemeChanged/, 'Renderer must follow live Windows theme changes');
assert.match(preferenceHook, /resolveDarkTheme\(preferences\.theme, systemDark\)/, 'System mode must resolve to the detected OS theme');
assert.match(preferenceHook, /theme: preferences\.theme/, 'Persistence must retain selected mode instead of flattening it to light/dark');
assert.match(preferenceHook, /themeModeVersion: 1/, 'The system mode migration must be stable after the first save');
assert.match(appearance, /preferences\.theme === 'system'/, 'Appearance must expose a selected System mode');
assert.match(appearance, /follow Windows/i, 'System mode must explain its behaviour');
assert.match(appearance, /preferences\.theme === 'light'/, 'Light selection must reflect the selected mode, not just resolved appearance');
assert.match(appearance, /preferences\.theme === 'dark'/, 'Dark selection must reflect the selected mode, not just resolved appearance');
assert.match(preload, /getSystemTheme:.*theme:get-system/, 'Secure preload must expose a read-only system theme method');
assert.match(preload, /onSystemThemeChanged:[\s\S]*theme:system-changed/, 'Secure preload must expose system theme updates with an unsubscribe');
assert.match(main, /nativeTheme\.on\('updated'/, 'Electron must broadcast Windows theme changes');
assert.match(main, /handle\('theme:get-system',\s*\(\)\s*=>\s*getSystemThemeName\(\)\)/, 'System theme IPC must use the trusted handler wrapper');
assert.match(splash, /pdfstudio-settings[\s\S]*prefers-color-scheme:\s*dark/, 'Startup splash should avoid a theme flash in system mode');
assert.match(splash, /themeModeVersion === 1/, 'The splash must follow the OS theme for old unversioned preferences');
assert.match(titlebar, /titlebar-status[\s\S]*Local workspace/, 'Local workspace status must use a stable styled status chip');
assert.match(css, /\.titlebar-status[\s\S]*background:\s*#f1f8f4/, 'Local status chip must have a styled light-theme surface');
assert.match(css, /theme-dark \.titlebar-status[\s\S]*background:\s*#202d27/, 'Local status chip must have a styled dark-theme surface');
assert.match(css, /\.setting-toggle-row\s*\{\s*position:\s*relative/, 'Checkbox must be contained in its toggle row to prevent scroll jumps');
assert.match(css, /\.setting-toggle-row input\s*\{[^}]*top:\s*50%;[^}]*right:\s*0;[^}]*transform:\s*translateY\(-50%\)/, 'Visually hidden checkbox must be anchored to its switch row');
assert.match(css, /Accessibility contrast changes colours and focus rings only/, 'Contrast styling must be explicitly layout-stable');
assert.match(toggle, /<input type="checkbox" checked=\{checked\}/, 'Settings toggles must preserve a real accessible checkbox');
console.log('System theme detection, local workspace indicator, and layout-stable contrast UX checks passed.');
